def build():
    legacy = json.load(open(LEGACY, encoding="utf-8"))
    assert legacy["track"] == "backend" and legacy["part"] == "b1"
    legacy_tasks = []
    for t in legacy["tasks"]:
        assert t.get("legacy") is True, t["task_id"]
        nt = copy.deepcopy(t)
        nt["explanation"] = txt(LEGACY_EXPLANATIONS[t["task_id"]])
        # защита: legacy не меняется ни в чём, кроме explanation
        for k in t:
            if k != "explanation":
                assert nt[k] == t[k], (t["task_id"], k)
        legacy_tasks.append(nt)
    assert set(LEGACY_EXPLANATIONS) == {t["task_id"] for t in legacy_tasks}

    # новые задачи не должны пересекаться с legacy и должны продолжать нумерацию
    legacy_ids = {t["task_id"] for t in legacy_tasks}
    last_legacy = {}
    for t in legacy_tasks:
        n = int(t["task_id"].rsplit("-", 1)[1])
        last_legacy[t["topic_id"]] = max(last_legacy.get(t["topic_id"], (0, 0)), (n, t["difficulty"]))
    for t in NEW:
        assert t["task_id"] not in legacy_ids, t["task_id"]
        if t["topic_id"] in last_legacy:
            ln, ld = last_legacy[t["topic_id"]]
            assert int(t["task_id"].rsplit("-", 1)[1]) > ln, t["task_id"]
            assert t["difficulty"] >= ld, t["task_id"]

    shuffle_options(NEW)
    tasks = legacy_tasks + NEW
    tasks.sort(key=lambda t: (TOPIC_ORDER.index(t["topic_id"]), t["task_id"]))

    data = {
        "track": "backend",
        "part": "b1",
        "topics": [{"topic_id": tid, "theory": txt(THEORY[tid])} for tid in TOPIC_ORDER],
        "tasks": tasks,
    }
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    for tid in TOPIC_ORDER:
        print("%-20s theory %4d симв., задач %d" % (tid, len(txt(THEORY[tid])),
                                                     sum(1 for t in tasks if t["topic_id"] == tid)))
    print("итого задач:", len(tasks), "->", OUT)


if __name__ == "__main__":
    build()
