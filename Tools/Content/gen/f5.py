XP_BASE = {1: 20, 2: 35, 3: 55, 4: 80, 5: 110}


def xp(d, grade="middle"):
    mult = {"intern": 1.0, "junior": 1.0, "junior_plus": 1.25, "middle": 1.5}[grade]
    return int(round(XP_BASE[d] * mult / 5.0)) * 5


def fix_quotes(story):
    """Внутри реплики «…» вложенные кавычки делаем “…”, как в эталонах."""
    i = story.find(": «")
    j = story.rfind("»")
    if i < 0 or j <= i or story[j + 1:] not in ("", "."):
        return story
    head, body, tail = story[:i + 3], story[i + 3:j], story[j:]
    return head + body.replace("«", "“").replace("»", "”") + tail


def shuffle_options(tid, options, answer):
    """В исходнике верные варианты идут первыми для читаемости; в выдаче — детерминированно перемешаны."""
    order = list(range(len(options)))
    random.Random("f5c:" + tid).shuffle(order)
    new_opts = [options[i] for i in order]
    pos = {old: new for new, old in enumerate(order)}
    new_ans = sorted(pos[i] for i in answer) if isinstance(answer, list) else pos[answer]
    right_before = {options[i] for i in (answer if isinstance(answer, list) else [answer])}
    right_after = {new_opts[i] for i in (new_ans if isinstance(new_ans, list) else [new_ans])}
    assert right_before == right_after, tid
    return new_opts, new_ans


def task(tid, typ, d, character, story, question, explanation, hints, code=None, language=None,
         options=None, answer=None, tests=None, entry=None, time_limit=None):
    topic = tid.rsplit("-", 1)[0]
    if options is not None:
        options, answer = shuffle_options(tid, options, answer)
    content = {"question": question, "code": code, "language": language}
    if entry:
        content["entry"] = entry
    content.update({"options": options, "correct_answer": answer, "test_cases": tests})
    return {
        "task_id": tid, "topic_id": topic, "grade": "middle", "type": typ, "difficulty": d,
        "xp_reward": xp(d), "time_limit_minutes": time_limit, "character": character,
        "story": fix_quotes(story), "content": content, "explanation": explanation, "hints": hints,
    }


