TOPICS.append({"topic_id": "fe-a11y", "theory": """Доступность (a11y) — это когда сайтом могут пользоваться все: незрячие с экранной читалкой, те, кто работает только с клавиатуры, слабовидящие с увеличением, люди с тремором. В ЕС это закон (European Accessibility Act применяется с июня 2025 года), у многих клиентов — пункт договора. Ориентир — WCAG 2.2 уровня AA.

Семантика — большая часть успеха. Нативные элементы бесплатно дают роль, фокус и клавиатуру:
• действие — <button>, переход — <a href>. div с onClick не получает фокус по Tab, не нажимается Enter и Space, а читалка не скажет, что это кнопка;
• заголовки h1–h6 по порядку, области header, nav, main, footer, списки ul/li — по ним читалка навигирует;
• первое правило ARIA: не используй ARIA, если есть нативный элемент. Неправильная ARIA хуже никакой.

Формы:
• у каждого поля видимый <label>, связанный через for/id (или обёрткой). placeholder исчезает при вводе и подписью не считается;
• радиокнопки группируй в fieldset с legend;
• ошибка: aria-invalid="true" на поле и aria-describedby с id текста ошибки — читалка прочитает её вместе с полем;
• появление ошибки надо озвучить: role="alert" (срочно) или контейнер с aria-live="polite", который есть в DOM заранее, а меняется только его текст;
• type="email", type="tel" и autocomplete дают нужную клавиатуру на телефоне и автозаполнение.

    <label for="phone">Телефон</label>
    <input id="phone" type="tel" aria-describedby="phone-error">
    <p id="phone-error" aria-live="polite"></p>

Картинки и иконки: alt передаёт смысл, а не слово «картинка»; у декоративной — alt="". Кнопке-иконке без текста нужно имя: aria-label="Закрыть", а сама svg — aria-hidden="true".

Клавиатура и фокус:
• до всего интерактивного можно дойти Tab в логичном порядке. tabindex="0" добавляет элемент в порядок, "-1" — только для программного фокуса, положительный tabindex ломает порядок всей страницы;
• outline: none без замены делает фокус невидимым — стилизуй :focus-visible;
• модальное окно: при открытии фокус переходит внутрь, Tab не уходит под оверлей, Escape закрывает, после закрытия фокус возвращается на кнопку, которая открыла окно. Нативный <dialog> с showModal() делает большую часть сам;
• самописные виджеты (календарь, слайдер, drag-and-drop) — самое дорогое: им нужна клавиатурная логика по паттернам WAI-ARIA APG или альтернативный способ сделать то же самое.

Контраст: обычный текст — не меньше 4.5:1, крупный (от 24px или от 18.66px жирным) и элементы интерфейса — 3:1. Цвет не должен быть единственным носителем смысла: ошибку дублируй текстом или иконкой.

Как проверять: пройти сценарий только клавиатурой; послушать читалкой (NVDA на Windows, VoiceOver на macOS и iOS, TalkBack на Android); axe DevTools или Lighthouse; eslint-plugin-jsx-a11y в CI. Автоматика находит лишь часть проблем, остальное — руками. Тесты с getByRole заодно проверяют, что у элементов есть роли и имена."""})

