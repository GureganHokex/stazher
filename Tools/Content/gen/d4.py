def topic(tid, theory):
    TOPICS.append({"topic_id": tid, "theory": theory.strip()})


def task(topic_id, n, typ, diff, char, story, question, explanation, hints,
         code=None, lang=None, options=None, answer=None, tests=None, entry=None, tl=None):
    if options is not None:
        # Детерминированно перемешиваем варианты, чтобы верный ответ не стоял всегда на одном месте
        perm = list(range(len(options)))
        random.Random("d4:%s-%02d" % (topic_id, n)).shuffle(perm)
        options = [options[i] for i in perm]
        if isinstance(answer, list):
            answer = sorted(perm.index(i) for i in answer)
        else:
            answer = perm.index(answer)
    content = {"question": question.strip(), "code": code, "language": lang}
    if entry:
        content["entry"] = entry
    content.update({"options": options, "correct_answer": answer, "test_cases": tests})
    TASKS.append({
        "task_id": "%s-%02d" % (topic_id, n),
        "topic_id": topic_id,
        "grade": "middle",
        "type": typ,
        "difficulty": diff,
        "xp_reward": xp(diff),
        "time_limit_minutes": tl,
        "character": char,
        "story": story.strip(),
        "content": content,
        "explanation": explanation.strip(),
        "hints": hints,
    })


def chk(desc, rx, flags="i"):
    return {"input": desc, "expected": {"regex": rx, "flags": flags}}


def nchk(desc, rx, flags="i"):
    return {"input": desc, "expected": {"not_regex": rx, "flags": flags}}


