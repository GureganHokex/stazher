def BUILD(wid, x=0.0):
    cname = "Weapon_" + wid
    coll = bpy.data.collections.get(cname)
    if coll:
        for o in list(coll.objects): bpy.data.objects.remove(o, do_unlink=True)
    else:
        coll = bpy.data.collections.new(cname); bpy.context.scene.collection.children.link(coll)
    r = GUNS[wid](coll); r.location.x = x
    return r

def BUILD_ALL(spacing=0.0):
    return {w: BUILD(w, i * spacing) for i, w in enumerate(GUNS)}

def EXPORT_ONE(wid, path):
    r = bpy.data.objects.get("W_" + wid)
    x0 = r.location.copy(); r.location = (0, 0, 0)
    objs = [r] + list(r.children_recursive)
    bpy.context.view_layer.update()
    for o in bpy.data.objects:
        try: o.select_set(False)
        except (RuntimeError, AttributeError): pass
    for o in objs:
        o.hide_viewport = False; o.hide_render = False
        try: o.hide_set(False); o.select_set(True)
        except RuntimeError: pass
    bpy.context.view_layer.objects.active = r
    bpy.ops.export_scene.fbx(filepath=path, use_selection=True, object_types={'MESH', 'EMPTY'},
                             use_mesh_modifiers=False, mesh_smooth_type='OFF', add_leaf_bones=False, bake_anim=False,
                             apply_unit_scale=True, apply_scale_options='FBX_SCALE_NONE', axis_forward='-Z', axis_up='Y', global_scale=1.0)
    for o in objs:
        try: o.select_set(False)
        except RuntimeError: pass
    r.location = x0
    return path

def EXPORT_ALL(out_dir):
    import os
    os.makedirs(out_dir, exist_ok=True)
    return [EXPORT_ONE(w, os.path.join(out_dir, w + ".fbx")) for w in GUNS]
