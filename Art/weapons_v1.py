def mat(n):
    m = bpy.data.materials.get(n)
    if m is None:
        m = bpy.data.materials.new(n); col, rough, met = MATS[n]
        m.diffuse_color = lin(col); m.roughness = rough; m.metallic = met
        m.use_nodes = True
        bs = m.node_tree.nodes.get("Principled BSDF")
        if bs:
            bs.inputs["Base Color"].default_value = lin(col); bs.inputs["Roughness"].default_value = rough; bs.inputs["Metallic"].default_value = met
    return m

def rrect(w, y0, y1, c, k=2, x0=0.0):
    """Скруглённый прямоугольник x∈[x0−w, x0+w], y∈[y0, y1], радиус углов c, k отрезков на угол — точки против часовой."""
    c = max(1e-5, min(c, w * 0.95, (y1 - y0) * 0.48))
    out = []
    for cx, cy, a0 in ((x0 + w - c, y1 - c, 0.0), (x0 - w + c, y1 - c, 90.0), (x0 - w + c, y0 + c, 180.0), (x0 + w - c, y0 + c, 270.0)):
        for i in range(k + 1):
            a = math.radians(a0 + 90.0 * i / k); out.append((cx + math.cos(a) * c, cy + math.sin(a) * c))
    return out

# ---------------------------------------------------------------- сборка детали
class Part:
    """Деталь: bmesh в координатах оружия (переводим в Blender при создании вершин), материалы по номерам."""
    def __init__(self, name, pivot=(0, 0, 0)):
        self.name = name; self.pivot = V(pivot); self.bm = bmesh.new(); self.mats = []
    def mi(self, m):
        if m not in self.mats: self.mats.append(m)
        return self.mats.index(m)
    def _new(self, pts, faces, m, bevel=0.0, sharp=30.0, fmats=None):
        vs = [self.bm.verts.new(B(p)) for p in pts]
        fs = []
        for i, f in enumerate(faces):
            try:
                face = self.bm.faces.new([vs[j] for j in f])
                face.material_index = self.mi(fmats[i] if fmats else m); fs.append(face)
            except ValueError: pass
        bmesh.ops.recalc_face_normals(self.bm, faces=fs)
        if bevel > 0:
            es = list({e for f in fs for e in f.edges if e.is_manifold and e.calc_face_angle(0) > math.radians(sharp)})
            if es:
                r = bmesh.ops.bevel(self.bm, geom=es, offset=bevel, offset_type='OFFSET', segments=1, profile=0.5, affect='EDGES', clamp_overlap=True)
                k = self.mi(m)
                for f in r.get('faces', []): f.material_index = k
        return fs

    def _rings(self, rings, m, caps=True, closed=False):
        n = len(rings[0]); P = [p for r in rings for p in r]; F = []
        R = len(rings)
        for i in range(R - 1 + (1 if closed else 0)):
            a, b = i % R, (i + 1) % R
            for k in range(n): F.append([a * n + k, a * n + (k + 1) % n, b * n + (k + 1) % n, b * n + k])
        if caps and not closed:
            F.append(list(range(n))[::-1]); F.append([(R - 1) * n + k for k in range(n)])
        return self._new(P, F, m)

    # призма из многоугольника (z, y) — вид сбоку, толщина по x
    def side(self, pts, x0, x1, m, bevel=0.0012):
        n = len(pts)
        P = [(x0, y, z) for z, y in pts] + [(x1, y, z) for z, y in pts]
        F = [list(range(n)), list(range(2 * n - 1, n - 1, -1))] + [[i, (i + 1) % n, n + (i + 1) % n, n + i] for i in range(n)]
        return self._new(P, F, m, bevel)
    def box(self, c, s, m, bevel=0.0008):
        x, y, z = c; a, b, d = s[0] / 2, s[1] / 2, s[2] / 2
        return self.side([(z - d, y - b), (z + d, y - b), (z + d, y + b), (z - d, y + b)], x - a, x + a, m, bevel)
    # лофт вдоль z: сечения (z, низ, верх, полуширина, радиус углов[, сдвиг по x])
    def zloft(self, secs, m, k=2, caps=True):
        rings = []
        for s in secs:
            z, y0, y1, w, c = s[:5]; x0 = s[5] if len(s) > 5 else 0.0
            rings.append([(x, y, z) for x, y in rrect(w, y0, y1, c, k, x0)])
        return self._rings(rings, m, caps)
    # лофт по пути в плоскости (z, y): сечения (z, y, полуширина по x, полутолщина поперёк пути, радиус углов)
    def ploft(self, secs, m, k=2, caps=True):
        rings = []; n = len(secs)
        for i, s in enumerate(secs):
            z, y, w, d, c = s
            a = secs[max(0, i - 1)]; b = secs[min(n - 1, i + 1)]
            tz, ty = b[0] - a[0], b[1] - a[1]; L = math.hypot(tz, ty) or 1.0; tz, ty = tz / L, ty / L
            vz, vy = -ty, tz                              # поперёк пути
            rings.append([(px, y + vy * pv, z + vz * pv) for px, pv in rrect(w, -d, d, c, k)])
        return self._rings(rings, m, caps)
    # тело вращения вдоль оси: prof — [(t, r)], центр c
    def lathe(self, prof, m, c=(0, 0, 0), axis='z', segs=16, caps=True, a0=0.0):
        c = V(c); rings = []
        for t, r in prof:
            ring = []
            for k in range(segs):
                a = a0 + TAU * k / segs; u, v = math.cos(a) * max(r, 1e-5), math.sin(a) * max(r, 1e-5)
                if axis == 'z': ring.append((c.x + u, c.y + v, c.z + t))
                elif axis == 'x': ring.append((c.x + t, c.y + u, c.z + v))
                else: ring.append((c.x + u, c.y + t, c.z + v))
            rings.append(ring)
        return self._rings(rings, m, caps)
    def cyl(self, a, b, r, m, segs=12):
        a, b = V(a), V(b); d = b - a; L = d.length; z = d / L
        x = V((1, 0, 0)) if abs(z.x) < 0.9 else V((0, 1, 0)); x = (x - z * x.dot(z)).normalized(); y = z.cross(x)
        rings = [[tuple(a + z * t + x * (math.cos(TAU * k / segs) * r) + y * (math.sin(TAU * k / segs) * r)) for k in range(segs)] for t in (0.0, L)]
        return self._rings(rings, m)
    def pin(self, c, r, m="wpn_dark", side=None, h=0.0012):
        """Штифт или винт на боку: кружок, выступающий из поверхности x = c.x (side — ±1, куда смотрит)."""
        x, y, z = c; s = side if side else (1 if x >= 0 else -1)
        return self.cyl((x, y, z), (x + s * h, y, z), r, m, segs=10)
    def ring(self, c, axis, R, r, m, segs=16, sides=6, arc=TAU, a0=0.0):
        c = V(c); zz = V(axis).normalized()
        x = V((1, 0, 0)) if abs(zz.x) < 0.9 else V((0, 1, 0)); x = (x - zz * x.dot(zz)).normalized(); y = zz.cross(x)
        closed = arc >= TAU - 1e-6; n = segs if closed else segs + 1
        rings = []
        for i in range(n):
            a = a0 + arc * i / segs; d = x * math.cos(a) + y * math.sin(a); cc = c + d * R
            rings.append([tuple(cc + d * (math.cos(TAU * k / sides) * r) + zz * (math.sin(TAU * k / sides) * r)) for k in range(sides)])
        return self._rings(rings, m, caps=not closed, closed=closed)
    def rail(self, z0, z1, y, w=0.0105, m="wpn_metal"):
        """Планка Пикатинни: основание и зубцы (шаг 10 мм)."""
        self.zloft([(z0, y - 0.004, y, w, 0.0012), (z1, y - 0.004, y, w, 0.0012)], m)
        n = int((z1 - z0) / 0.010)
        for i in range(n):
            z = z0 + 0.0025 + i * 0.010
            self.zloft([(z, y, y + 0.0035, w, 0.0008), (z + 0.0052, y, y + 0.0035, w, 0.0008)], m, k=1)
    def blade(self, st, tip, m="wpn_blade", me="wpn_edge", g=0.42):
        """Клинок: станции (z, верх-обух, низ-кромка, полутолщина обуха) и острие (z, y). Спуск к кромке — светлее."""
        rings = []
        for z, ys, ye, ts in st:
            yg = ye + (ys - ye) * g; tg = ts * 0.8
            rings.append([(0.0, ye, z), (-tg, yg, z), (-ts, ys, z), (ts, ys, z), (tg, yg, z)])
        P = [p for r in rings for p in r] + [(0.0, tip[1], tip[0])]
        n = 5; F = []; FM = []
        for i in range(len(rings) - 1):
            for k in range(n):
                F.append([i * n + k, i * n + (k + 1) % n, (i + 1) * n + (k + 1) % n, (i + 1) * n + k]); FM.append(me if k in (0, 4) else m)
        t = len(P) - 1; last = (len(rings) - 1) * n
        for k in range(n): F.append([last + k, last + (k + 1) % n, t]); FM.append(me if k in (0, 4) else m)
        F.append(list(range(n))[::-1]); FM.append(m)
        return self._new(P, F, m, fmats=FM)

    def build(self, parent):
        me = bpy.data.meshes.new(self.name)
        bmesh.ops.remove_doubles(self.bm, verts=self.bm.verts[:], dist=1e-6)
        bmesh.ops.recalc_face_normals(self.bm, faces=self.bm.faces[:])
        ng = [f for f in self.bm.faces if len(f.verts) > 4]      # многоугольники — сразу в треугольники
        if ng: bmesh.ops.triangulate(self.bm, faces=ng, quad_method='BEAUTY', ngon_method='EAR_CLIP')
        piv = B(self.pivot)
        for v in self.bm.verts: v.co -= piv
        self.bm.to_mesh(me); self.bm.free()
        for m in self.mats: me.materials.append(mat(m))
        for p in me.polygons: p.use_smooth = True
        try: me.set_sharp_from_angle(angle=math.radians(48))
        except Exception: pass
        ob = bpy.data.objects.new(self.name, me)
        parent.users_collection[0].objects.link(ob)
        ob.parent = parent; ob.location = piv
        return ob

def anchor(parent, name, p, size=0.01):
    e = bpy.data.objects.new("A_" + name, None); e.empty_display_size = size; e.empty_display_type = 'SPHERE'
    parent.users_collection[0].objects.link(e); e.parent = parent; e.location = B(p)
    return e

def root(coll, wid):
    r = bpy.data.objects.new("W_" + wid, None); r.empty_display_size = 0.05; coll.objects.link(r)
    anchor(r, "AxisX", (0.1, 0, 0)); anchor(r, "AxisY", (0, 0.1, 0)); anchor(r, "AxisZ", (0, 0, 0.1))
    return r

def anchors(r, A):
    for k, p in A.items(): anchor(r, k, p)

def trigger_part(r, z, y, m="wpn_dark", curve=1.0):
    """Спусковой крючок: изогнутый язычок, ось вращения сверху."""
    t = Part("Trigger", pivot=(0, y, z))
    pts = [(z + 0.002, y), (z + 0.007, y), (z + 0.005, y - 0.010 * curve), (z - 0.001, y - 0.018 * curve), (z - 0.006, y - 0.020 * curve),
           (z - 0.005, y - 0.016 * curve), (z - 0.0005, y - 0.010 * curve)]
    t.side(pts, -0.0032, 0.0032, m, 0.0006); t.build(r)

def guard(b, z0, z1, y, depth=0.024, m="wpn_polymer", w=0.0055, t=0.0045):
    """Спусковая скоба: петля под спуском от z0 (сзади) до z1 (спереди) от высоты y вниз на depth."""
    yb = y - depth
    b.zloft([(z0 + 0.003, yb, yb + t, w, 0.0015), (z1 - 0.004, yb, yb + t, w, 0.0015)], m)
    b.ploft([(z1 - 0.006, yb + t * 0.5, w, t * 0.5, 0.0012), (z1 + 0.001, yb + 0.006, w, t * 0.5, 0.0012), (z1 + 0.002, y - 0.006, w, t * 0.5, 0.0012),
             (z1 - 0.002, y + 0.001, w, t * 0.5, 0.0012)], m)
    b.ploft([(z0 + 0.004, yb + t * 0.5, w, t * 0.5, 0.0012), (z0 - 0.001, yb + 0.006, w, t * 0.5, 0.0012), (z0, y - 0.004, w, t * 0.5, 0.0012)], m)

