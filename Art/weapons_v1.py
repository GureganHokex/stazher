TAU = 2 * math.pi
def B(p): return V((-p[0], -p[2], p[1]))          # координаты оружия → Blender

def lin(h):
    c = int(h, 16); r, g, b = (c >> 16) & 255, (c >> 8) & 255, c & 255
    f = lambda x: (x / 255.0) ** 2.2
    return (f(r), f(g), f(b), 1.0)

